def gq(s):
    out=['"']
    for ch in s:
        o=ord(ch)
        if ch=='"': out.append('\\"')
        elif ch=='\\': out.append('\\\\')
        elif 0x20<=o<0x7f: out.append(ch)
        elif o<0x80: out.append('\\x%02x'%o)
        elif o<0x10000: out.append('\\u%04x'%o)
        else: out.append('\\U%08x'%o)
    out.append('"'); return ''.join(out)

def gb(b):
    return '"'+''.join('\\x%02x'%x for x in b)+'"'

